/* Store code rules shared by the report page (classic script → window.StoreCodes) and the Telegram bot (require()).
   The supported reports come from data/registry.js (generated by the fixture builder from the fixture's store metadata). */
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.StoreCodes = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';
  var EXAMPLE = 'ST-13204';
  var MSG = {
    format: function (ask) { return 'Харилцагчийн кодоо ' + EXAMPLE + ' эсвэл 13204 хэлбэрээр ' + ask + '.'; },   // bot: «илгээнэ үү», page: «оруулна уу»
    unsupported: function (sample) { return 'Энэ кодын тайлан демод бэлэн биш байна. Турших код: ' + sample + '.'; }
  };
  // the WHOLE text must be a code: «ST-13204» (any case, outer spaces) or exactly five digits «13204»; nothing is picked out of a sentence
  function normalize(text) {
    var s = String(text == null ? '' : text).trim();
    var m = /^ST-(\d{5})$/i.exec(s) || /^(\d{5})$/.exec(s);
    return m ? 'ST-' + m[1] : null;
  }
  // → { status: 'ok', code, store } | { status: 'unsupported', code } | { status: 'format' }
  function resolve(text, registry) {
    var code = normalize(text);
    if (!code) return { status: 'format' };
    var store = registry && registry.stores && registry.stores[code];
    return store ? { status: 'ok', code: code, store: store } : { status: 'unsupported', code: code };
  }
  function sampleCode(registry) { var k = Object.keys((registry && registry.stores) || {}); return k[0] || EXAMPLE; }
  function message(result, registry, verb) { return result.status === 'format' ? MSG.format(verb || 'илгээнэ үү') : result.status === 'unsupported' ? MSG.unsupported(sampleCode(registry)) : ''; }
  // one-line place/channel text from registry metadata (plain text; callers never inject it as HTML/Markdown)
  function place(store) { return [store.aimag, store.channel].filter(Boolean).join(' · '); }
  return { EXAMPLE: EXAMPLE, normalize: normalize, resolve: resolve, message: message, sampleCode: sampleCode, place: place };
});
